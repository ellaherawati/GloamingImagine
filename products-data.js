// Helper: ambil produk berdasarkan array of IDs
// Dipakai oleh wishlist.php
// ============================================================
function getProductsByIds(ids) {
    // ids dari localStorage tersimpan sebagai number atau string,
    // pastikan perbandingan pakai == agar keduanya cocok
    return ids
        .map(id => products.find(p => p.id == id))
        .filter(p => p !== undefined);
}